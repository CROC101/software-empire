// Generates src/data/sources.generated.ts: the TypeScript source of every component in
// src/components/reactbits plus a JavaScript variant (types stripped by the TS compiler).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, basename } from "node:path";
import ts from "typescript";

const dir = join(process.cwd(), "src/components/reactbits");
const out = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".tsx")).sort()) {
  const tsSrc = readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n");
  const js = ts.transpileModule(tsSrc, {
    compilerOptions: { jsx: ts.JsxEmit.Preserve, target: ts.ScriptTarget.ESNext, module: ts.ModuleKind.ESNext },
  }).outputText;
  out[basename(file, ".tsx")] = { ts: tsSrc, js: js.replace(/^export \{\};\n?/m, "") };
}
if (Object.keys(out).length < 10) throw new Error(`expected 10 components, found ${Object.keys(out).length}`);
writeFileSync(
  join(process.cwd(), "src/data/sources.generated.ts"),
  `// AUTO-GENERATED by scripts/gen-sources.mjs. Do not edit.\nexport const sources: Record<string, { ts: string; js: string }> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`gen-sources: ${Object.keys(out).length} components`);
