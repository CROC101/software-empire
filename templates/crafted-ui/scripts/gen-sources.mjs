// Embeds each registry component's real source so the code viewer, prompt and registry JSON never drift from what runs.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../src/registry/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".tsx")).sort();
const map = Object.fromEntries(files.map((f) => [f.replace(/\.tsx$/, ""), readFileSync(new URL(f, dir), "utf8").replace(/\r\n/g, "\n")]));
writeFileSync(
  new URL("../src/data/registry-sources.ts", import.meta.url),
  `// Generated by scripts/gen-sources.mjs. Do not edit.\nexport const SOURCES: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`,
);
console.log(`registry sources: ${files.length} files`);
